/**
 * Bundles the installation and licensing guide (docs/GUIDE.md + docs/GUIDE.he.md) into the API build, like the
 * extension docs (gen-extension-docs.ts): the public docs site serves it at /api/docs/guide[/he] and the app shows it
 * in its own shell (GET /guides/install), and the deployed image must not depend on the repository's docs/ folder.
 *   pnpm --filter @bines/api docs:guide
 * Writes src/modules/apidocs/install-guide.generated.ts. test/install-guide.test.ts fails when it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = resolve(here, '../../../docs');
const out = resolve(here, '../src/modules/apidocs/install-guide.generated.ts');

/** The Markdown as committed, with LF line ends (a Windows checkout may have CRLF). */
export const readGuide = (file: 'GUIDE.md' | 'GUIDE.he.md') =>
  readFileSync(join(docsDir, file), 'utf8').replace(/\r\n/g, '\n');

const source = `// Generated by apps/api/scripts/gen-install-guide.ts from docs/GUIDE.md and docs/GUIDE.he.md — do not edit by hand.
// Regenerate: pnpm --filter @bines/api docs:guide

export const INSTALL_GUIDE_EN_MD: string = ${JSON.stringify(readGuide('GUIDE.md'))};

export const INSTALL_GUIDE_HE_MD: string = ${JSON.stringify(readGuide('GUIDE.he.md'))};
`;

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // Formatted like the rest of the repo, so `pnpm format:check` stays green after a regeneration.
  writeFileSync(out, await format(source, { ...(await resolveConfig(out)), filepath: out }));
  console.warn(`wrote ${out}`);
}
