/**
 * Bundles the extension developer docs (docs/extensions/*.md) into the API build (s37docs): the public docs site
 * serves them at /api/docs/extensions, and the deployed image must not depend on the repository's docs/ folder.
 *   pnpm --filter @bines/api docs:extensions
 * Writes src/modules/apidocs/extension-docs.generated.ts. test/extension-docs.test.ts fails when it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = resolve(here, '../../../docs/extensions');
const out = resolve(here, '../src/modules/apidocs/extension-docs.generated.ts');

/** The Markdown as committed, with LF line ends (a Windows checkout may have CRLF). */
export const readDoc = (file: string) => readFileSync(join(docsDir, file), 'utf8').replace(/\r\n/g, '\n');

const source = `// Generated by apps/api/scripts/gen-extension-docs.ts from docs/extensions/*.md — do not edit by hand.
// Regenerate: pnpm --filter @bines/api docs:extensions

export const EXTENSION_GUIDE_MD: string = ${JSON.stringify(readDoc('README.md'))};

export const EXTENSION_QUICKSTART_MD: string = ${JSON.stringify(readDoc('QUICKSTART.md'))};
`;

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // Formatted like the rest of the repo, so `pnpm format:check` stays green after a regeneration.
  writeFileSync(out, await format(source, { ...(await resolveConfig(out)), filepath: out }));
  console.warn(`wrote ${out}`);
}
