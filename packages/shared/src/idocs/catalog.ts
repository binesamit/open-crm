export type IdocPreset = {
  key: string;
  group: IdocGroup;
  kind: IdocSectionKind;
  label: { he: string; en: string };
  description: { he: string; en: string };
  /** Starting settings (merged over the kind's defaults). */
  patch: Record<string, unknown>;
  soon?: boolean;
};

const p = (
  key: string,
  group: IdocGroup,
  kind: IdocSectionKind,
  he: string,
  en: string,
  dHe: string,
  dEn: string,
  patch: Record<string, unknown> = {},
  soon = false,
): IdocPreset => ({
  key,
  group,
  kind,
  label: { he, en },
  description: { he: dHe, en: dEn },
  patch,
  ...(soon ? { soon } : {}),
});

