/**
 * The "add section" catalog (canvas part 2b): ready presets over the generic section engines.
 * A preset is only a kind + starting settings + a name — after adding, every setting is editable. Presets marked
 * `soon` need an engine that does not exist yet; the builder lists them disabled.
 */
