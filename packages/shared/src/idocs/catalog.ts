export const idocPreset = (key: string) => IDOC_PRESETS.find((x) => x.key === key);

/** A new section from a preset (a fresh id is given by the caller). */
export const sectionFromPreset = (key: string, id: string): IdocSection | null => {
  const preset = idocPreset(key);
  if (!preset || preset.soon) return null;
  return newIdocSection(preset.kind, id, { ...preset.patch, preset: key });
};
